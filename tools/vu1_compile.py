#!/usr/bin/env python3
"""vu1_compile.py [--files N] <outdir> <dump>...: compile VU1 microcode into C++ blocks for the PS2Recomp runner.

Each <dump> is a vu1-<hash>.bin code image (16 KiB) with an optional vu1-<hash>.entries list of hex pcs
that runs started at (directories are searched for both). Blocks start at the entries and at every static
branch target or return address reachable from them, and run to the next block start or to the delay slot
of an unconditional jump or E-bit. A block is keyed by its pc and words, so images that share a program
share its blocks. VU1Interpreter binds a block wherever the uploaded code matches its words; everything
else stays interpreted. Writes N (default 8) files <outdir>/vu1_blocks_<n>.cpp.
"""
import glob, os, sys

CODE_SIZE = 0x4000
MAX_PAIRS = 512
FILES = 8


def words(img, pc):
    return int.from_bytes(img[pc:pc + 4], "little"), int.from_bytes(img[pc + 4:pc + 8], "little")


def imm11(lower):
    v = lower & 0x7FF
    return v - 0x800 if v & 0x400 else v


def control(img, pc):
    """(ends the block after the next pair, static targets) of the pair at pc."""
    lower, upper = words(img, pc)
    targets = []
    ends = bool(upper & 0x40000000)  # E bit
    if not upper & 0x80000000:  # lower is an instruction, not the I immediate
        op = lower >> 25
        if op in (0x20, 0x21) or 0x28 <= op <= 0x2F and op not in (0x2A, 0x2B):
            targets.append((pc + 8 + imm11(lower) * 8) & (CODE_SIZE - 1))
        if op in (0x21, 0x25):
            targets.append((pc + 16) & (CODE_SIZE - 1))
        ends |= op in (0x20, 0x21, 0x24, 0x25)
    return ends, targets


def block_starts(img, entries):
    starts, work = set(), list(entries)
    while work:
        pc = work.pop()
        if pc in starts or pc % 8 or pc >= CODE_SIZE:
            continue
        starts.add(pc)
        while pc < CODE_SIZE:
            ends, targets = control(img, pc)
            work.extend(targets)
            if ends:
                if pc + 8 < CODE_SIZE:
                    work.extend(control(img, pc + 8)[1])
                break
            pc += 8
    return starts


def blocks_of(img, starts):
    for start in sorted(starts):
        pc, n = start, 0
        while pc < CODE_SIZE and n < MAX_PAIRS and (pc == start or pc not in starts):
            ends, _ = control(img, pc)
            n += 1
            if pc == start and pc >= 8 and control(img, pc - 8)[0]:
                break  # a delay slot: the program ends or jumps after it
            if ends:
                n += pc + 8 < CODE_SIZE
                break
            pc += 8
        yield start, img[start:start + n * 8]


def load(paths):
    images = {}
    for path in paths:
        files = sorted(glob.glob(os.path.join(path, "vu1-*.bin"))) if os.path.isdir(path) else [path]
        for f in files:
            img = open(f, "rb").read()
            if len(img) != CODE_SIZE:
                sys.exit("%s: not a %d-byte VU1 code image" % (f, CODE_SIZE))
            entries = {0}
            ef = f[:-4] + ".entries"
            if os.path.exists(ef):
                entries |= {int(line, 16) for line in open(ef) if line.strip()}
            images.setdefault(img, set()).update(entries)
    return images


def emit(out, blocks):
    os.makedirs(out, exist_ok=True)
    for old in glob.glob(os.path.join(out, "vu1_blocks_*.cpp")):
        os.remove(old)
    per_file = (len(blocks) + FILES - 1) // FILES
    for n in range(FILES):
        chunk = blocks[n * per_file:(n + 1) * per_file]
        if not chunk:
            break
        src = ["// Generated by tools/vu1_compile.py: VU1 microcode compiled into blocks. Do not edit.",
               "// The VU rounds toward zero at run time, so keep the compiler from folding float math in nearest.",
               "#pragma GCC optimize(\"rounding-math\")",
               "#include \"runtime/ps2_vu1_exec.h\"",
               "",
               "namespace",
               "{",
               "using A = VU1Interpreter::CompiledAccess;",
               ""]
        table = []
        for i, (pc, code) in enumerate(chunk):
            name = "b%04x_%d" % (pc, i)
            src.append("int %s(VU1Interpreter &vu, uint64_t end)" % name)
            src.append("{")
            pairs = len(code) // 8
            for k in range(pairs):
                lower, upper = words(code, k * 8)
                nxt = (pc + (k + 1) * 8) % CODE_SIZE
                src.append("    if (const int r = A::step<0x%08Xu, 0x%08Xu>(vu, end, 0x%04Xu)) return r;" % (lower, upper, nxt))
            src.append("    return A::kLeave;")
            src.append("}")
            ws = ", ".join("0x%08Xu" % int.from_bytes(code[j:j + 4], "little") for j in range(0, len(code), 4))
            src.append("const uint32_t %s_words[] = {%s};" % (name, ws))
            src.append("")
            table.append("    {0x%04Xu, %du, %s_words, %s}," % (pc, pairs, name, name))
        src.append("const VU1Interpreter::CompiledBlock kBlocks[] = {")
        src.extend(table)
        src.append("};")
        src.append("const bool kRegistered = (VU1Interpreter::registerCompiledBlocks(kBlocks, std::size(kBlocks)), true);")
        src.append("}")
        with open(os.path.join(out, "vu1_blocks_%d.cpp" % n), "w") as f:
            f.write("\n".join(src) + "\n")


def main():
    global FILES
    args = sys.argv[1:]
    if args[:1] == ["--files"]:
        FILES, args = int(args[1]), args[2:]
    if len(args) < 2:
        sys.exit(__doc__)
    images = load(args[1:])
    blocks = {}
    for img, entries in images.items():
        for pc, code in blocks_of(img, block_starts(img, entries)):
            blocks[(pc, code)] = True
    ordered = sorted(blocks)
    emit(args[0], ordered)
    print("%d images -> %d blocks, %d pairs" % (len(images), len(ordered), sum(len(c) // 8 for _, c in ordered)))


if __name__ == "__main__":
    main()
